-- Aido: associations post missions, volunteers apply in-app, both sides talk per application.

create schema if not exists private;

create or replace function private.set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Organizations ---------------------------------------------------------------
-- Rows are created by the server after checking the national register, so clients cannot insert
-- or touch verification columns.
create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null unique references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 2 and 200),
  country_code text not null default 'FR' check (char_length(country_code) = 2),
  national_id text not null,
  national_id_type text not null check (national_id_type in ('siren', 'rna')),
  verified boolean not null default false,
  verified_at timestamptz,
  city text,
  postal_code text,
  description text check (char_length(description) <= 2000),
  website text check (char_length(website) <= 300),
  contact_email text check (char_length(contact_email) <= 320),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
comment on table public.organizations is 'Associations using Aido. One per owner account in v1.';
create unique index organizations_national_id_key on public.organizations (country_code, national_id) where deleted_at is null;

-- Missions --------------------------------------------------------------------
create table public.missions (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations (id) on delete cascade,
  title text not null check (char_length(title) between 3 and 160),
  description text not null check (char_length(description) <= 5000),
  country_code text not null default 'FR' check (char_length(country_code) = 2),
  city text,
  postal_code text,
  admin_area_code text,
  lat double precision,
  lon double precision,
  location_mode text not null default 'onsite' check (location_mode in ('onsite', 'remote', 'hybrid')),
  commitment text not null default 'unknown' check (commitment in ('one-off', 'short-term', 'long-term', 'ongoing', 'unknown')),
  cause text not null default 'other',
  skills text[] not null default '{}',
  schedule_text text check (char_length(schedule_text) <= 200),
  start_date date,
  end_date date,
  places integer check (places is null or places > 0),
  -- [{ "id": "q1", "label": "...", "kind": "short" | "long" | "yes_no" }]
  questions jsonb not null default '[]'::jsonb check (jsonb_typeof(questions) = 'array'),
  status text not null default 'draft' check (status in ('draft', 'published', 'closed')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
comment on column public.missions.questions is 'Short application form generated by AI from the association''s description or old PDF form.';
create index missions_listing_idx on public.missions (country_code, status) where deleted_at is null;
create index missions_organization_idx on public.missions (organization_id);

-- Volunteer profiles ----------------------------------------------------------
create table public.volunteer_profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  first_name text check (char_length(first_name) <= 80),
  contact_email text check (char_length(contact_email) <= 320),
  phone text check (char_length(phone) <= 40),
  city text check (char_length(city) <= 120),
  about text check (char_length(about) <= 1500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Applications ----------------------------------------------------------------
create table public.applications (
  id uuid primary key default gen_random_uuid(),
  mission_id uuid not null references public.missions (id) on delete cascade,
  volunteer_id uuid not null references auth.users (id) on delete cascade,
  -- [{ "questionId": "q1", "question": "...", "answer": "..." }]
  answers jsonb not null default '[]'::jsonb check (jsonb_typeof(answers) = 'array'),
  motivation text check (char_length(motivation) <= 2000),
  fit_summary text check (char_length(fit_summary) <= 600),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined', 'withdrawn')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (mission_id, volunteer_id)
);
create index applications_volunteer_idx on public.applications (volunteer_id);

create table public.application_messages (
  id uuid primary key default gen_random_uuid(),
  application_id uuid not null references public.applications (id) on delete cascade,
  sender_id uuid not null references auth.users (id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index application_messages_application_idx on public.application_messages (application_id, created_at);

-- updated_at triggers -----------------------------------------------------------
create trigger organizations_updated_at before update on public.organizations for each row execute function private.set_updated_at();
create trigger missions_updated_at before update on public.missions for each row execute function private.set_updated_at();
create trigger volunteer_profiles_updated_at before update on public.volunteer_profiles for each row execute function private.set_updated_at();
create trigger applications_updated_at before update on public.applications for each row execute function private.set_updated_at();

-- Ownership helpers (security definer avoids recursive RLS checks) ----------------
create or replace function private.owns_organization(target_org uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.organizations o
    where o.id = target_org and o.owner_id = (select auth.uid()) and o.deleted_at is null
  );
$$;

create or replace function private.owns_mission(target_mission uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.missions m
    join public.organizations o on o.id = m.organization_id
    where m.id = target_mission and o.owner_id = (select auth.uid()) and o.deleted_at is null
  );
$$;

create or replace function private.is_application_participant(target_application uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.applications a
    join public.missions m on m.id = a.mission_id
    join public.organizations o on o.id = m.organization_id
    where a.id = target_application
      and (a.volunteer_id = (select auth.uid()) or o.owner_id = (select auth.uid()))
  );
$$;

create or replace function private.applied_to_my_mission(target_volunteer uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.applications a
    join public.missions m on m.id = a.mission_id
    join public.organizations o on o.id = m.organization_id
    where a.volunteer_id = target_volunteer and o.owner_id = (select auth.uid())
  );
$$;

grant usage on schema private to authenticated, anon;
grant execute on all functions in schema private to authenticated, anon;

-- Row level security ----------------------------------------------------------------
alter table public.organizations enable row level security;
alter table public.missions enable row level security;
alter table public.volunteer_profiles enable row level security;
alter table public.applications enable row level security;
alter table public.application_messages enable row level security;

-- organizations: public profile, owner edits non-verification fields.
create policy "organizations are publicly readable" on public.organizations
  for select to anon, authenticated using (deleted_at is null);
create policy "owners update their organization" on public.organizations
  for update to authenticated using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
revoke insert, update, delete on public.organizations from anon, authenticated;
grant update (name, city, postal_code, description, website, contact_email) on public.organizations to authenticated;

-- missions: published ones are public; owners manage their own.
create policy "published missions are publicly readable" on public.missions
  for select to anon, authenticated using (status = 'published' and deleted_at is null);
create policy "owners read their missions" on public.missions
  for select to authenticated using ((select private.owns_organization(organization_id)));
create policy "owners create missions" on public.missions
  for insert to authenticated with check ((select private.owns_organization(organization_id)));
create policy "owners update missions" on public.missions
  for update to authenticated
  using ((select private.owns_organization(organization_id)))
  with check ((select private.owns_organization(organization_id)));
revoke delete on public.missions from anon, authenticated;

-- volunteer profiles: self, plus associations the volunteer applied to.
create policy "volunteers read own profile" on public.volunteer_profiles
  for select to authenticated using (user_id = (select auth.uid()));
create policy "associations read applicant profiles" on public.volunteer_profiles
  for select to authenticated using ((select private.applied_to_my_mission(user_id)));
create policy "volunteers create own profile" on public.volunteer_profiles
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy "volunteers update own profile" on public.volunteer_profiles
  for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- applications: volunteer applies to published missions; both sides read; status changes only.
create policy "participants read applications" on public.applications
  for select to authenticated
  using (volunteer_id = (select auth.uid()) or (select private.owns_mission(mission_id)));
create policy "volunteers apply to published missions" on public.applications
  for insert to authenticated
  with check (
    volunteer_id = (select auth.uid())
    and exists (select 1 from public.missions m where m.id = mission_id and m.status = 'published' and m.deleted_at is null)
  );
create policy "participants update application status" on public.applications
  for update to authenticated
  using (volunteer_id = (select auth.uid()) or (select private.owns_mission(mission_id)))
  with check (volunteer_id = (select auth.uid()) or (select private.owns_mission(mission_id)));
revoke insert, update, delete on public.applications from anon, authenticated;
grant insert (mission_id, volunteer_id, answers, motivation) on public.applications to authenticated;
grant update (status) on public.applications to authenticated;

-- messages: only the two sides of an application.
create policy "participants read messages" on public.application_messages
  for select to authenticated using ((select private.is_application_participant(application_id)));
create policy "participants send messages" on public.application_messages
  for insert to authenticated
  with check (sender_id = (select auth.uid()) and (select private.is_application_participant(application_id)));
revoke update, delete on public.application_messages from anon, authenticated;
